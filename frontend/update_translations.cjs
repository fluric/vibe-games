const langs = ['de', 'fr', 'es'];
const mapping = {
  de: deTranslations,
  fr: frTranslations,
  es: esTranslations
};

langs.forEach(lang => {
  const filePath = `/Users/cfl/Dev/vibe-games/frontend/src/i18n/locales/${lang}.json`;
  const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  
  if (!data.lobby) data.lobby = {};
  for (const [k, v] of Object.entries(mapping[lang])) {
    data.lobby[k] = v;
  }
  
  if (!data.game) data.game = {};
  for (const [k, v] of Object.entries(gameTranslations[lang])) {
    data.game[k] = v;
  }
  
  fs.writeFileSync(filePath, JSON.stringify(data, null, 2) + '\n');
});

console.log("Translations successfully updated.");
